// UI screenshots: title, wizard, camp, draft, shop, map, pause. node scripts/uicheck.mjs <outPrefix> [w] [h]
import { chromium } from '@playwright/test';
const [out, w = '1400', h = '820'] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h }, hasTouch: +w < 900, isMobile: +w < 900 });
const errors = [];
page.on('pageerror', (e) => errors.push('PAGEERROR ' + String(e.stack || e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(`${m.type()}: ${m.text()}`); });
await page.goto('http://127.0.0.1:5190/');
await page.waitForFunction(() => window.__realmApi, null, { timeout: 60000 });
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}-title.png` });
await page.click('[data-act=play]'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-mode.png` });
await page.click('.wizard .next'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-hero.png` });
await page.click('.wizard .next'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-diff.png` });
await page.click('.wizard .next'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-chapter.png` });
await page.click('.wizard .back'); await page.click('.wizard .back'); await page.click('.wizard .back'); await page.click('.wizard .back');
await page.waitForTimeout(300);
await page.click('[data-act=camp]'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-talents.png` });
await page.click('[data-tab=shop]'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-metashop.png` });
await page.click('[data-tab=codex]'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-codex.png` });
await page.click('[data-sub=enemies]'); await page.waitForTimeout(300); await page.evaluate(() => document.querySelector('.codex-item:nth-child(20)')?.scrollIntoView()); await page.screenshot({ path: `${out}-codex-enemies.png` });
await page.click('.camp .back');
await page.evaluate(() => window.__realmApi.startRun({ mode: 'adventure', hero: 'knight', difficulty: 'normal', chapter: 1 }));
await page.waitForFunction(() => window.__realmApi.game?.status === 'map', null, { timeout: 60000 });
await page.waitForTimeout(500); await page.screenshot({ path: `${out}-map.png` });
await page.evaluate(() => document.querySelector('.mnode.avail').click());
await page.waitForTimeout(3000);
await page.evaluate(() => { const g = window.__realmApi.game; g.player.invuln = 99; g.addXp(g.xpToNext() * 1.5); });
await page.waitForFunction(() => window.__realmApi.game?.status === 'draft', null, { timeout: 10000 });
await page.waitForTimeout(700); await page.screenshot({ path: `${out}-draft.png` });
await page.keyboard.press('Digit1'); await page.waitForTimeout(300);
await page.evaluate(() => { window.__realmApi.game.inventory.gold = 5000; });
await page.keyboard.press('KeyB'); await page.waitForTimeout(400); await page.screenshot({ path: `${out}-shop.png` });
await page.click('[data-tab=upgrades]'); await page.waitForTimeout(200); await page.click('[data-id=i_cleaver]'); await page.waitForTimeout(300); await page.screenshot({ path: `${out}-shop2.png` });
await page.keyboard.press('KeyB'); await page.waitForTimeout(200);
await page.keyboard.press('Escape'); await page.waitForTimeout(400); await page.screenshot({ path: `${out}-pause.png` });
console.log(errors.slice(0, 20).join('\n') || 'no errors');
await browser.close();
